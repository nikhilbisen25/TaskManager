#!/usr/bin/env bash
# Writes /opt/taskmanager/.env on the EC2 instance. Run as root (setup.sh runs it via SSM).
#   make-env.sh <rds_host> <ecr_registry> <aws_region> <rds_master_secret_arn>
# Secrets are GENERATED HERE, on the instance, so they never pass through a laptop, GitHub or chat.
# Re-running keeps existing secrets and only updates the non-secret values.
set -euo pipefail
[ $# -eq 4 ] || { echo "usage: $0 <rds_host> <ecr_registry> <aws_region> <rds_master_secret_arn>" >&2; exit 2; }

cd /opt/taskmanager
if [ -f .env ]; then
  # shellcheck disable=SC1091
  source .env
  echo "Existing .env found: keeping its secrets."
fi

JWT_SECRET="${JWT_SECRET:-$(openssl rand -hex 32)}"
AUTH_DB_PASSWORD="${AUTH_DB_PASSWORD:-$(openssl rand -hex 24)}"
TASK_DB_PASSWORD="${TASK_DB_PASSWORD:-$(openssl rand -hex 24)}"

umask 077
cat > .env <<EOF
# Generated by make-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Root-only. Never copy into git.
AWS_REGION=$3
ECR_REGISTRY=$2
RDS_HOST=$1
RDS_SECRET_ARN=$4
JWT_SECRET=$JWT_SECRET
JWT_EXPIRE_MINUTES=${JWT_EXPIRE_MINUTES:-60}
AUTH_DB_PASSWORD=$AUTH_DB_PASSWORD
TASK_DB_PASSWORD=$TASK_DB_PASSWORD
EOF
chmod 600 .env
echo "Wrote /opt/taskmanager/.env (secrets not printed)."
